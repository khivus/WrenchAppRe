const UI_KEY: &str = "bytes:ui";
const GROUPS_KEY: &str = "bytes:droneBlah2";

// Generated by tools/drone-catalog from the SDE and the refine fitting engine.
// Newer copies are fetched from the repository at runtime; the schema guards
// older app versions against a format they can't read.
const CATALOG_JSON: &str = include_str!("../data/drone_groups.json");
const CATALOG_SCHEMA: u32 = 1;
const REMOTE_CATALOG_URL: &str = "https://raw.githubusercontent.com/eve-wrench/eve-wrench-app/main/crates/eve-wrench-core/data/drone_groups.json";
const CACHE_FILE: &str = "drone_groups.json";

// Text outside brackets is always written; a [bracketed] section is dropped
// when a token inside it has no value for the drone (sentries have no speed).
pub const DEFAULT_PATTERN: &str =
    "{name}[ | {damage}][ | {dps}][ | {effect}][ | {speed}][ | {range}]";

pub const PATTERN_STYLES: [(&str, &str); 3] = [
    ("detailed", DEFAULT_PATTERN),
    ("compact", "{name}[ {damage}][ {dps}][ {effect}]"),
    ("plain", "{name}"),
];

pub const PATTERN_TOKENS: [&str; 8] = [
    "name",
    "type",
    "type_short",
    "damage",
    "dps",
    "speed",
    "range",
    "effect",
];

#[derive(Deserialize, Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[serde(rename_all = "lowercase")]
pub enum DroneCategory {
    Light,
    Medium,
    Heavy,
    Sentry,
    Special,
    Ewar,
    Logistics,
    Industry,
}

impl DroneCategory {
    fn naming_type(self) -> (&'static str, &'static str) {
        match self {
            Self::Light => ("Light", "Lgt"),
            Self::Medium => ("Medium", "Med"),
            Self::Heavy => ("Heavy", "Hev"),
            Self::Sentry => ("Sentry", "Sen"),
            Self::Special => ("Special", "Spec"),
            Self::Ewar => ("EWAR", "Ewar"),
            Self::Logistics => ("Logistic", "Logi"),
            Self::Industry => ("Industry", "Ind"),
        }
    }

    pub fn id(&self) -> &'static str {
        match self {
            Self::Light => "light",
            Self::Medium => "medium",
            Self::Heavy => "heavy",
            Self::Sentry => "sentry",
            Self::Special => "special",
            Self::Ewar => "ewar",
            Self::Logistics => "logistics",
            Self::Industry => "industry",
        }
    }
}

// Max-skill numbers of the drone a preset is named after.
#[derive(Deserialize, Debug, Clone, Default, PartialEq)]
pub struct DroneStats {
    pub damage: Option<String>,
    // DPS of a full flight
    pub dps: Option<f64>,
    // m/s; absent for sentries
    pub speed: Option<f64>,
    // Meters; only for sentries
    pub optimal: Option<f64>,
    pub falloff: Option<f64>,
    // Repair, yield or EWAR strength, already formatted
    pub effect: Option<String>,
}

#[derive(Deserialize, Debug, Clone, PartialEq)]
pub struct DroneGroupPreset {
    pub id: String,
    pub name: String,
    pub category: DroneCategory,
    pub group_id: i64,
    // The drone whose icon represents the group; absent in older catalogs
    #[serde(default)]
    pub type_id: Option<i64>,
    pub members: Vec<String>,
    pub stats: DroneStats,
}

impl DroneGroupPreset {
    fn token(&self, token: &str) -> Option<String> {
        let stats = &self.stats;
        match token {
            "name" => Some(self.name.clone()),
            "type" => Some(self.category.naming_type().0.to_string()),
            "type_short" => Some(self.category.naming_type().1.to_string()),
            "damage" => stats.damage.clone(),
            "dps" => stats.dps.map(|dps| format!("{dps:.0}dps")),
            "speed" => stats.speed.map(|speed| format!("{}m/s", kilo(speed))),
            "range" => stats.optimal.map(|optimal| match stats.falloff {
                Some(falloff) => format!("{}+{}m", kilo(optimal), kilo(falloff)),
                None => format!("{}m", kilo(optimal)),
            }),
            "effect" => stats.effect.clone(),
            _ => None,
        }
    }

    // The group name under `pattern`, or under the default one when the
    // pattern is invalid.
    pub fn label(&self, pattern: &str) -> String {
        let parts = parse_pattern(pattern)
            .or_else(|_| parse_pattern(DEFAULT_PATTERN))
            .unwrap_or_default();
        let mut out = String::new();
        for part in &parts {
            match part {
                Part::Optional(inner) => {
                    if let Some(text) = self.render_all(inner) {
                        out.push_str(&text);
                    }
                }
                Part::Token(token) => out.push_str(&self.token(token).unwrap_or_default()),
                Part::Text(text) => out.push_str(text),
            }
        }
        out.trim().to_string()
    }

    fn render_all(&self, parts: &[Part]) -> Option<String> {
        parts.iter().try_fold(String::new(), |mut out, part| {
            match part {
                Part::Text(text) => out.push_str(text),
                Part::Token(token) => out.push_str(&self.token(token)?),
                Part::Optional(_) => unreachable!("sections do not nest"),
            }
            Some(out)
        })
    }
}

#[derive(Debug, Clone, PartialEq)]
pub enum PatternError {
    MissingName,
    UnknownToken(String),
    Unbalanced,
}

impl fmt::Display for PatternError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::MissingName => write!(
                f,
                "Include {{name}} outside optional [sections]; it can go anywhere in the pattern"
            ),
            Self::UnknownToken(token) => write!(f, "Unknown token {{{token}}}"),
            Self::Unbalanced => write!(f, "Unbalanced brackets or braces"),
        }
    }
}

enum Part {
    Text(String),
    Token(String),
    Optional(Vec<Part>),
}

fn parse_pattern(pattern: &str) -> Result<Vec<Part>, PatternError> {
    let mut parts = Vec::new();
    let mut section: Option<Vec<Part>> = None;
    let mut chars = pattern.chars();
    let mut text = String::new();

    fn flush(text: &mut String, section: &mut Option<Vec<Part>>, parts: &mut Vec<Part>) {
        if !text.is_empty() {
            let part = Part::Text(std::mem::take(text));
            section.as_mut().unwrap_or(parts).push(part);
        }
    }

    while let Some(c) = chars.next() {
        match c {
            '{' => {
                flush(&mut text, &mut section, &mut parts);
                let mut token = String::new();
                loop {
                    match chars.next() {
                        Some('}') => break,
                        Some(c) => token.push(c),
                        None => return Err(PatternError::Unbalanced),
                    }
                }
                if !PATTERN_TOKENS.contains(&token.as_str()) {
                    return Err(PatternError::UnknownToken(token));
                }
                section
                    .as_mut()
                    .unwrap_or(&mut parts)
                    .push(Part::Token(token));
            }
            '[' if section.is_none() => {
                flush(&mut text, &mut section, &mut parts);
                section = Some(Vec::new());
            }
            ']' if section.is_some() => {
                flush(&mut text, &mut section, &mut parts);
                parts.push(Part::Optional(section.take().unwrap_or_default()));
            }
            '[' | ']' | '}' => return Err(PatternError::Unbalanced),
            c => text.push(c),
        }
    }
    if section.is_some() {
        return Err(PatternError::Unbalanced);
    }
    flush(&mut text, &mut section, &mut parts);
    if !parts
        .iter()
        .any(|part| matches!(part, Part::Token(token) if token == "name"))
    {
        return Err(PatternError::MissingName);
    }
    Ok(parts)
}

pub fn validate_pattern(pattern: &str) -> Result<(), PatternError> {
    parse_pattern(pattern).map(|_| ())
}

// 4200 -> "4.2k", 4000 -> "4k", 688 -> "688"
fn kilo(value: f64) -> String {
    if value >= 1000.0 {
        format!("{:.1}k", value / 1000.0).replace(".0k", "k")
    } else {
        format!("{value:.0}")
    }
}

#[derive(Deserialize)]
struct CatalogFile {
    schema: u32,
    sde_build: u64,
    presets: Vec<DroneGroupPreset>,
}

struct Catalog {
    sde_build: u64,
    presets: Arc<[DroneGroupPreset]>,
}

fn parse_catalog(text: &str) -> Result<Catalog, String> {
    let file: CatalogFile =
        serde_json::from_str(text).map_err(|e| format!("Invalid drone catalog: {e}"))?;
    if file.schema != CATALOG_SCHEMA {
        return Err(format!("Unsupported drone catalog schema {}", file.schema));
    }
    if file.presets.is_empty() {
        return Err("Drone catalog has no presets".into());
    }
    Ok(Catalog {
        sde_build: file.sde_build,
        presets: file.presets.into(),
    })
}

fn current() -> &'static RwLock<Catalog> {
    static CURRENT: OnceLock<RwLock<Catalog>> = OnceLock::new();
    CURRENT.get_or_init(|| {
        RwLock::new(parse_catalog(CATALOG_JSON).expect("bundled drone catalog is valid"))
    })
}

// Takes over a catalog built from a newer SDE than the one in use.
fn install(catalog: Catalog) -> bool {
    let mut current = current().write().unwrap_or_else(|e| e.into_inner());
    if catalog.sde_build <= current.sde_build {
        return false;
    }
    *current = catalog;
    true
}

// Presets in display order: by category, then size.
pub fn catalog() -> Arc<[DroneGroupPreset]> {
    let current = current().read().unwrap_or_else(|e| e.into_inner());
    current.presets.clone()
}

// The catalog downloaded on an earlier run, when it is newer than the one
// built into this version.
pub fn load_cached_catalog(data_dir: &Path) {
    if let Some(catalog) = fs::read_to_string(data_dir.join(CACHE_FILE))
        .ok()
        .and_then(|text| parse_catalog(&text).ok())
    {
        install(catalog);
    }
}

// Fetches the latest catalog, which CI regenerates after each SDE release, and
// caches it when it is newer. Returns whether the presets changed.
pub fn refresh_catalog(data_dir: &Path) -> Result<bool, String> {
    let text = AGENT
        .get(REMOTE_CATALOG_URL)
        .call()
        .map_err(|e| format!("Failed to fetch drone catalog: {e}"))?
        .body_mut()
        .read_to_string()
        .map_err(|e| format!("Failed to read drone catalog: {e}"))?;
    if !install(parse_catalog(&text)?) {
        return Ok(false);
    }
    fs::create_dir_all(data_dir).map_err(|e| e.to_string())?;
    fs::write(data_dir.join(CACHE_FILE), text).map_err(|e| e.to_string())?;
    Ok(true)
}

fn stored_groups(root: &Value) -> Option<&Map<String, Value>> {
    root.get(UI_KEY)
        .and_then(|ui| ui.get(GROUPS_KEY))
        .and_then(|v| v.get("tuple"))
        .and_then(|t| t.get(1))
        .and_then(|v| v.as_object())
}

fn group_label(key: &str, group: &Value) -> String {
    let label = group
        .get("bytes:label")
        .and_then(|v| v.as_str())
        .unwrap_or(key);
    strip_type_prefix(label).to_string()
}

fn has_drones(group: &Value) -> bool {
    group
        .get("bytes:droneIDs")
        .and_then(|ids| ids.as_array())
        .is_some_and(|ids| !ids.is_empty())
}

// Copy definitions/favorites without importing another account's drone items.
// Keep the identities of matching target groups and all occupied target-only
// groups, so existing memberships (and references) survive the operation.
pub(crate) fn preserve_assignments(root: &mut Value, target: &Value) -> Result<(), String> {
    fn groups(root: &Value) -> Result<Map<String, Value>, String> {
        let Some(ui) = root.get(UI_KEY) else {
            return Ok(Map::new());
        };
        let ui = ui
            .as_object()
            .ok_or("Drone settings 'ui' section is invalid")?;
        let Some(value) = ui.get(GROUPS_KEY) else {
            return Ok(Map::new());
        };
        let groups = value
            .get("tuple")
            .and_then(Value::as_array)
            .filter(|tuple| tuple.len() == 2)
            .and_then(|tuple| tuple[1].as_object())
            .ok_or("Drone group settings are invalid")?;
        for group in groups.values() {
            let group = group.as_object().ok_or("Drone group entry is invalid")?;
            if group
                .get("bytes:droneIDs")
                .is_some_and(|ids| !ids.is_array())
            {
                return Err("Drone group membership is invalid".into());
            }
        }
        Ok(groups.clone())
    }

    let mut copied = groups(root)?;
    let target_groups = groups(target)?;
    let mut retained = HashSet::new();
    let mut remapped = Vec::new();
    for (key, group) in &mut copied {
        let label = group_label(key, group);
        let matches: Vec<_> = target_groups
            .iter()
            .filter(|(key, group)| group_label(key, group) == label)
            .collect();
        if matches.len() > 1 {
            return Err("Target has ambiguous drone group names".into());
        }
        let old_id = group.get("bytes:id").cloned();
        let fields = group
            .as_object_mut()
            .ok_or("Drone group entry is invalid")?;
        if let Some((target_key, target_group)) = matches.first() {
            if !retained.insert((*target_key).clone()) {
                return Err("Source has ambiguous drone group names".into());
            }
            if fields.get("bytes:droneGroupID") != target_group.get("bytes:droneGroupID") {
                // A name collision between different drone categories must not
                // move the target's drones into an incompatible definition.
                *group = (*target_group).clone();
            } else {
                fields.insert(
                    "bytes:droneIDs".into(),
                    target_group
                        .get("bytes:droneIDs")
                        .cloned()
                        .unwrap_or_else(|| json!([])),
                );
                if let Some(id) = target_group.get("bytes:id") {
                    fields.insert("bytes:id".into(), id.clone());
                }
            }
        } else {
            fields.insert("bytes:droneIDs".into(), json!([]));
        }
        if let (Some(old_id), Some(new_id)) = (old_id, group.get("bytes:id"))
            && old_id != *new_id
        {
            remapped.push((old_id, new_id.clone()));
        }
    }
    for (key, group) in target_groups {
        if !retained.contains(&key) && has_drones(&group) {
            if copied.contains_key(&key) {
                return Err("Drone group name collision would lose target assignments".into());
            }
            copied.insert(key, group);
        }
    }

    if copied.is_empty() && root.get(UI_KEY).and_then(|ui| ui.get(GROUPS_KEY)).is_none() {
        return Ok(());
    }
    let ui = root
        .as_object_mut()
        .ok_or("Settings file has an unexpected structure")?
        .entry(UI_KEY)
        .or_insert_with(|| json!({}))
        .as_object_mut()
        .ok_or("Drone settings 'ui' section is invalid")?;
    let stored = ui
        .entry(GROUPS_KEY)
        .or_insert_with(|| json!({"tuple": [format!("long:{}", filetime_now()), {}]}));
    stored["tuple"][1] = Value::Object(copied);
    for (key, value) in ui {
        if strip_type_prefix(key).starts_with("drones_favoriteGroupID_")
            && let Some(favorite) = value.get_mut("tuple").and_then(|tuple| tuple.get_mut(1))
            && let Some((_, new_id)) = remapped.iter().find(|(old_id, _)| old_id == favorite)
        {
            *favorite = new_id.clone();
        }
    }
    Ok(())
}

// The longest whole family or drone name anywhere in the label:
// "Lgt | Hobgoblin" is the Hobgoblin family, "EWAR | Hobgoblin SD-300" the
// light sensor damp group. Boundaries prevent "Hobgoblins" matching Hobgoblin.
// Known token values may touch the name, as in "LgtHobgoblin".
fn name_boundary(mut context: &str, tokens: &[String], before: bool) -> bool {
    loop {
        let adjacent = if before {
            context.chars().next_back()
        } else {
            context.chars().next()
        };
        if adjacent.is_none_or(|c| !c.is_alphanumeric()) {
            return true;
        }
        let rest = tokens
            .iter()
            .filter(|token| !token.is_empty())
            .filter_map(|token| {
                if before {
                    context.strip_suffix(token.as_str())
                } else {
                    context.strip_prefix(token.as_str())
                }
            })
            .min_by_key(|rest| rest.len());
        let Some(rest) = rest else { return false };
        context = rest;
    }
}

fn matching_preset<'a>(
    presets: &'a [DroneGroupPreset],
    label: &str,
) -> Option<&'a DroneGroupPreset> {
    presets
        .iter()
        .flat_map(|preset| {
            std::iter::once(preset.name.as_str())
                .chain(preset.members.iter().map(String::as_str))
                .map(move |name| (name, preset))
        })
        .filter(|(name, preset)| {
            label.match_indices(name).any(|(start, _)| {
                let mut tokens: Vec<_> = PATTERN_TOKENS
                    .iter()
                    .filter_map(|token| match *token {
                        "name" => None,
                        _ => preset.token(token),
                    })
                    .collect();
                // Recognize groups saved before short types were capitalized.
                tokens.push(preset.category.naming_type().1.to_ascii_lowercase());
                // Recognize light groups saved under the former Small/Sml names.
                if preset.category == DroneCategory::Light {
                    tokens.extend(["Small", "Sml", "sml"].map(str::to_string));
                }
                name_boundary(&label[..start], &tokens, true)
                    && name_boundary(&label[start + name.len()..], &tokens, false)
            })
        })
        .max_by_key(|(name, _)| name.len())
        .map(|(_, preset)| preset)
}

// Exact pattern matches also cover adjacent tokens, e.g. {type_short}{name}.
fn matching_preset_with_pattern<'a>(
    presets: &'a [DroneGroupPreset],
    label: &str,
    pattern: &str,
) -> Option<&'a DroneGroupPreset> {
    let mut exact = presets
        .iter()
        .filter(|preset| preset.label(pattern) == label);
    match (exact.next(), exact.next()) {
        (Some(preset), None) => Some(preset),
        (None, _) => matching_preset(presets, label),
        _ => None,
    }
}

fn present_in_settings(
    root: &Value,
    presets: &[DroneGroupPreset],
    pattern: &str,
) -> HashSet<String> {
    stored_groups(root)
        .into_iter()
        .flatten()
        .filter_map(|(key, group)| {
            matching_preset_with_pattern(presets, &group_label(key, group), pattern)
        })
        .map(|p| p.id.clone())
        .collect()
}

fn group_entry(preset: &DroneGroupPreset, label: &str, drone_ids: Value, created: Value) -> Value {
    let label = format!("utf8:{label}");
    json!({
        "bytes:droneGroupID": preset.group_id,
        "bytes:droneIDs": drone_ids,
        "bytes:id": {"tuple": [label.clone(), created]},
        "bytes:label": label,
    })
}

fn presets_into_settings(
    root: &mut Value,
    presets: &[DroneGroupPreset],
    selected: &HashSet<String>,
    pattern: &str,
) -> Result<(), String> {
    let now = filetime_now();
    let mut groups = Map::new();
    let mut written = HashSet::new();
    let stored: Vec<(&String, &Value, Option<&DroneGroupPreset>)> = stored_groups(root)
        .into_iter()
        .flatten()
        .map(|(key, group)| {
            (
                key,
                group,
                matching_preset_with_pattern(presets, &group_label(key, group), pattern),
            )
        })
        .collect();

    // A selected preset takes over one group matching it, renamed but keeping
    // its drones. The group already carrying the new name wins, so no other
    // group can end up under the same key.
    let mut owners: HashMap<&str, &String> = HashMap::new();
    for (key, group, preset) in &stored {
        let Some(preset) = preset.filter(|p| selected.contains(&p.id)) else {
            continue;
        };
        if group_label(key, group) == preset.label(pattern)
            || !owners.contains_key(preset.id.as_str())
        {
            owners.insert(&preset.id, key);
        }
    }

    // Groups that match no preset stay as they are. Any other matching group
    // is dropped only when it holds no drones, so a deselect never loses a
    // player's assignments.
    for (key, group, preset) in &stored {
        match preset {
            Some(preset) if owners.get(preset.id.as_str()) == Some(key) => {
                written.insert(preset.id.clone());
                let drone_ids = group.get("bytes:droneIDs").cloned().unwrap_or(json!([]));
                let created = group
                    .get("bytes:id")
                    .and_then(|id| id.get("tuple"))
                    .and_then(|t| t.get(1))
                    .cloned()
                    .unwrap_or_else(|| json!(format!("bytes:{now}")));
                let label = preset.label(pattern);
                groups.insert(
                    format!("utf8:{label}"),
                    group_entry(preset, &label, drone_ids, created),
                );
            }
            Some(_) if !has_drones(group) => {}
            _ => {
                groups.insert((*key).clone(), (*group).clone());
            }
        }
    }

    // Distinct creation stamps keep the client's group ids unique
    for (i, preset) in presets.iter().enumerate() {
        if selected.contains(&preset.id) && written.insert(preset.id.clone()) {
            let created = json!(format!("bytes:{}", now + i as u64));
            let label = preset.label(pattern);
            groups.insert(
                format!("utf8:{label}"),
                group_entry(preset, &label, json!([]), created),
            );
        }
    }

    root.as_object_mut()
        .ok_or("Settings file has an unexpected structure")?
        .entry(UI_KEY.to_string())
        .or_insert_with(|| json!({}))
        .as_object_mut()
        .ok_or("Settings 'ui' section has an unexpected structure")?
        .insert(
            GROUPS_KEY.to_string(),
            json!({"tuple": [format!("long:{now}"), groups]}),
        );
    Ok(())
}

// Ids of the catalog presets the account already has.
pub fn read_drone_groups(path: &Path) -> Result<HashSet<String>, String> {
    read_drone_groups_with_pattern(path, DEFAULT_PATTERN)
}

pub fn read_drone_groups_with_pattern(
    path: &Path,
    pattern: &str,
) -> Result<HashSet<String>, String> {
    let (json, _) = load_settings_json(path)?;
    Ok(present_in_settings(&json, &catalog(), pattern))
}

pub fn write_drone_groups(
    path: &Path,
    selected: &HashSet<String>,
    pattern: &str,
    backup: bool,
) -> Result<(), String> {
    validate_pattern(pattern).map_err(|e| e.to_string())?;
    if !path.exists() {
        return Err("Settings file does not exist".into());
    }
    if backup {
        auto_backup(path, "pre-drone-groups")?;
    }

    let (mut json, had_crc) = load_settings_json(path)?;
    presets_into_settings(&mut json, &catalog(), selected, pattern)?;
    let bytes = encode_settings_json(&json, had_crc)?;
    fs::write(path, bytes).map_err(|e| format!("Failed to write settings file: {}", e))
}

